function normalizar(texto: string) {
  return texto
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/^[A-Z]\d{5}\s*-\s*/, "")
    .replace(/[^A-Z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function tokensDistintivos(texto: string) {
  return normalizar(texto)
    .split(" ")
    .filter((token) => token.length >= 3 && !stopWords.has(token));
}

