function contaFornecedor(emitente: string) {
  const alvo = normalizar(emitente);
  const alvoTokens = tokensDistintivos(emitente);

  const direto = fornecedoresAnaliticos
    .filter((item) => alvo.length >= 8 && (item.normalizado.includes(alvo) || alvo.includes(item.normalizado)))
    .sort((a, b) => b.normalizado.length - a.normalizado.length)[0];
  if (direto) return direto.conta;

  const candidatos = fornecedoresAnaliticos
    .map((item) => {
      const intersecao = alvoTokens.filter((token) => item.tokens.includes(token));
      const base = Math.min(alvoTokens.length, item.tokens.length);
      const score = base > 0 ? intersecao.length / base : 0;
      return { ...item, intersecao: intersecao.length, score };
    })
    .filter((item) =>
      (item.intersecao >= 2 && item.score >= 0.8)
      || (item.intersecao === 1 && item.score === 1 && alvoTokens.some((token) => token.length >= 10 && item.tokens.includes(token))),
    )
    .sort((a, b) => b.score - a.score || b.intersecao - a.intersecao);

  if (candidatos.length === 1) return candidatos[0].conta;
  if (candidatos.length > 1 && candidatos[0].score > candidatos[1].score) return candidatos[0].conta;
  return "1496";
}

